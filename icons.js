// Build an SVG for one icon: a dark outline around the colored pixels, then the pixels.
const pxCache = {};
function pxIcon(name, cls = "") {
  const key = name + "|" + cls;
  if (pxCache[key]) return pxCache[key];
  const map = PX_ICONS[name];
  if (!map) return "";
  const H = map.length, W = map[0].length;
  const at = (r, c) => (r >= 0 && r < H && c >= 0 && c < W) ? map[r][c] : ".";
  // Grow the picture by one pixel in every direction for the outline.
  const grid = [];
  for (let r = 0; r < H; r++) {
    grid.push([]);
    for (let c = 0; c < W; c++) {
      let ch = at(r, c);
      if (ch === "." && [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dr, dc]) => at(r + dr, c + dc) !== ".")) ch = "k";
      grid[r].push(ch);
    }
  }
  // One <rect> per run of same-colored pixels in a row keeps the SVG small.
  let rects = "";
  for (let r = 0; r < H; r++) {
    let c = 0;
    while (c < W) {
      const ch = grid[r][c];
      let end = c + 1;
      while (end < W && grid[r][end] === ch) end++;
      if (ch !== "." && PX_COLORS[ch]) rects += `<rect x="${c}" y="${r}" width="${end - c}" height="1" fill="${PX_COLORS[ch]}"/>`;
      c = end;
    }
  }
  const svg = `<svg class="px-icon ${cls}" viewBox="0 0 ${W} ${H}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  pxCache[key] = svg;
  return svg;
}

// ---------- Emoji -> pixel icons ----------
// The game's text still uses emoji as short names for things ("💧 3", "🔥 Fire").
// emo() swaps each one for the matching pixel icon right before it goes on the page,
// so every label, button, log line and popup shows the same pixel art.
// Text inside tags (like title="..." tooltips) is left alone: tooltips can't show pictures.
const EMOJI_ICONS = {
  // stats
  "❤": "heart", "⚔": "adventure", "🛡": "hero", "💨": "gust", "🍀": "clover", "🗡": "adventure",
  // elements
  "🔥": "fire", "❄": "snow", "🌪": "tornado", "🪨": "rock", "⚡": "bolt",
  // status effects
  "☠": "skull", "🧊": "cube", "💫": "dizzy", "🥀": "wilt", "🧱": "brick",
  // money, menu and the rest
  "🪙": "coin", "👻": "souls", "⛏": "mine", "🔨": "forge", "⬆": "upgrades", "📜": "merchant",
  "💧": "drop", "🎁": "gift", "🏆": "trophy", "🏃": "run", "⚠": "warn", "👑": "crown", "💥": "boom",
  "📣": "horn", "📯": "horn", "🔁": "cycle", "🎲": "dice", "💤": "zzz", "✋": "hand", "✨": "sparkle",
  "🪤": "net", "📖": "book", "✕": "close", "◀": "left", "▶": "right",
  // danger level zones
  "🌿": "z_moss", "🕳": "z_hole", "🌋": "z_volcano", "🏔": "z_peak", "💎": "z_gem",
  "🏛": "z_ruins", "🌨": "z_tundra", "🏜": "z_wastes", "🌑": "z_abyss", "🌌": "z_stars",
};
const EMOJI_SRC = `(?:${Object.keys(EMOJI_ICONS).join("|")})\uFE0F?`;
const EMOJI_ANY = new RegExp(EMOJI_SRC, "u");
const EMOJI_ALL = new RegExp(EMOJI_SRC, "gu");

function emo(html) {
  html = String(html);
  if (!EMOJI_ANY.test(html)) return html;
  return html.split(/(<[^>]*>)/).map((part, i) => i % 2 ? part
    : part.replace(EMOJI_ALL, m => pxIcon(EMOJI_ICONS[m.replace(/\uFE0F/g, "")], "ti") || m)).join("");
}

function escapeHtml(text) {
  return String(text).replace(/[&<>"]/g, ch => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[ch]);
}

// Put plain text in a node, with pixel icons for its emoji. Only touches the page when the text changes.
function setIconText(node, text) {
  if (!node || node.dataset.txt === text) return;
  node.dataset.txt = text;
  if (EMOJI_ANY.test(text)) node.innerHTML = emo(escapeHtml(text));
  else node.textContent = text;
}

// Same for a bit of HTML.
function setIconHTML(node, html) {
  if (!node || node.dataset.html === html) return;
  node.dataset.html = html;
  node.innerHTML = emo(html);
}
