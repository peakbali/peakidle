// ---------- Monsters and bosses: small hand-drawn pixel sprites ----------
// Every creature and boss is a little text map: one letter = one pixel, "." = empty.
// A map marked `mirror: true` only holds the left half: the right half is the same, flipped.
// The painter (monster-pix.js) adds the dark outline, the blinking eyes and the flickering magic.
//
// Random monsters (20x20) are colored by their element, so a "Blazing Rat" is fiery orange and a
// "Frozen Rat" icy blue:
//   1 2 3 4 5 = the element's colors, from darkest to brightest
//   e         = an eye (blinks)            k = near-black          w = white
//   b B       = bone, horns, tusks          p = pink (ears, noses, tails)
//   y Y       = beaks, gold                 g G = light and dark grey (legs)
//   s         = skin                        c C = cream belly and its shade      r = red
//   m n c     = main body, darker parts (wings, shells, spines) and belly: these shade themselves
//               (lit on the top and left, darker on the bottom and right)
//   E         = glowing eyes (for dark creatures)    F = the element's glow (flames, sparks)
// `fx: true` adds element particles that drift around the creature (embers, ice shards, rocks...).
//
// Bosses (32x32) have their own colors, set in each boss's `pal`. E = eyes (blink), F = magic (flickers).
// Every boss gets particles of its element.
//
// `anim` picks the creature's idle animation (see "Monster art" in style.css):
//   breathe, hop, float, flap, scuttle, sway, pulse
// Needs pxSpriteHTML from monster-pix.js.

