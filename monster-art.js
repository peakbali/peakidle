// ---------- Pixel-art monsters and bosses ----------
// Every creature and boss gets a pixel picture drawn in code, like the gear and skill pictures.
// Each picture is a little text map: one letter = one pixel, "." = empty.
// A map marked `mirror: true` only holds the left half: the right half is the same, flipped.
//
// Random monsters (16x16) are colored by their element, so a "Blazing Rat" is fiery orange and a
// "Frozen Rat" icy blue:
//   a b c d e = the element's colors, from darkest to brightest (same as the skill pictures)
//   E         = glowing eyes            k = near-black        w = white
//   t         = teeth, bone, tusks      r = red mouth          g G = dark and light grey (claws, legs)
//   s         = skin                    n = dark brown         y = gold
//
// Bosses (32x32) have their own colors, set in each boss's `pal`. Two letters are special:
//   E = eyes and F = magic (flames, crystals, runes). Both glow and pulse in the game.
//
// `anim` picks the creature's idle animation (see "Monster art" in style.css):
//   breathe, hop, float, flap, scuttle, sway, pulse
// Needs pixelArtSVG from gear-art.js and SKILL_ELEMENT_COLORS from skill-art.js.

